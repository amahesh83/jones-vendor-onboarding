test('15 route editor, tester and Finance-owned call-back journey', async ({ page }) => {
  await login(page, 'adam')
  const cfg = await (await page.request.get('/api/internal/config')).json()
  const save = async routes => {
    await login(page, 'adam')
    const out = await page.request.put('/api/internal/admin/routes', { data: { routes, requesterReviewEnabled: true }, headers: { 'x-requested-with': 'VOB' } })
    expect(out.ok(), await out.text()).toBeTruthy()
  }
  try {
    await page.goto('/internal/#/admin/routes')
    await page.locator('#addRoute').click()
    const card = page.locator('.route-card').last()
    await card.locator('[data-field="name"]').fill('Browser low-risk Finance')
    await card.locator('[data-field="priority"]').fill('1')
    await card.locator('[data-condition="accountTypes"][value="YBIV"]').check()
    await card.locator('[data-field="bankCheckMode"]').selectOption('IN_FINANCE')
    await expect(card.locator('.banner.warn')).toContainText('removes the two-person check')
    // Exercise add/reorder/remove and validation, then restore the low-risk sequence.
    await card.locator('[data-add-step]').selectOption('PURCHASING')
    await card.getByRole('button', { name: 'Move Finance earlier', exact: true }).click()
    await page.locator('#saveRoutes').click()
    await expect(page.locator('#routeMessage')).toContainText('Finance must be last')
    await card.getByRole('button', { name: 'Move Finance later', exact: true }).click()
    await card.getByRole('button', { name: 'Remove Purchasing', exact: true }).click()
    await page.locator('#test_accountType').selectOption('YBIV')
    await page.locator('#test_paymentTerms').selectOption('60EOM')
    await page.locator('#testRoute').click()
    await expect(page.locator('#routeTestResult')).toContainText('Browser low-risk Finance: Requester → Finance')
    await page.locator('#saveRoutes').click()
    await expect(page.locator('#routeMessage')).toContainText('Routes saved')
    const r = await prepared(page)
    await approve(page, r.ID, 'rachel')
    await detail(page, r.ID, 'fiona')
    await expect(page.locator('#app')).toContainText('Route: Requester → Finance')
    await expect(page.locator('#bSave')).toBeVisible()
    await page.locator('#fSim').click()
    await expect(page.locator('.banner.ok').filter({ hasText: 'Simulation passed' })).toBeVisible()
    await expect(page.locator('#approve')).toBeDisabled()
    await page.locator('#fillCallback').click()
    await expect(page.locator('#bNum')).toHaveValue('+35315550100')
    const recorded = page.waitForResponse(r => r.url().endsWith('/bank-verification') && r.request().method() === 'POST')
    await page.locator('#bSave').click()
    expect((await recorded).ok()).toBeTruthy()
    await expect(page.locator('#approve')).toBeEnabled()
    await page.locator('#approve').click()
    await expect.poll(async () => (await (await page.request.get(`/api/internal/requests/${r.ID}`)).json()).request.status).toBe('CREATED')
    // Rule changes cannot alter the already-created request's route.
    await save(cfg.approvalRoutes)
    const d = await (await page.request.get(`/api/internal/requests/${r.ID}`)).json()
    expect(d.route.name).toBe('Browser low-risk Finance')
  } finally { await save(cfg.approvalRoutes) }
})
