'use strict'
const { test } = require('@playwright/test')
const H = require('./helpers')
test('all screens: responsive layout, keyboard and axe', async ({ page, context }, info) => {
  test.setTimeout(300000)
  await context.setExtraHTTPHeaders({ 'x-forwarded-for': '127.0.2.' + (info.project.name === '375-light' ? 1 : info.project.name === '375-dark' ? 2 : info.project.name === '1280-light' ? 3 : 4) })
  const scan = label => H.check(page, label, info)
  await page.goto('/'); await scan('landing')
  await page.goto('/how-it-works.html'); await scan('how-it-works')
  await page.goto('/internal/'); await H.expect(page.locator('[data-p]').first()).toBeVisible(); await scan('personas')
  await H.login(page); await page.reload(); await H.expect(page.locator('.kpi').first()).toBeVisible(); await scan('dashboard')
  await page.locator('#inviteBtn').click(); await scan('invite-dialog')
  await page.keyboard.press('Shift+Tab'); await H.expect(page.locator('#iGo')).toBeFocused()
  await page.keyboard.press('Escape'); await H.expect(page.locator('#inviteBtn')).toBeFocused()
  const r = await H.invite(page, { accountType: 'YBCS', paymentTerms: '30EOM' })
  await page.goto(r.devLink); await scan('vendor-welcome')
  await H.openVendor(page, r, scan)
  await H.fillVendor(page, r, scan)
  await scan('vendor-documents')
  for (const code of ['BANK_LETTER', 'TAX_CLEARANCE', 'INSURANCE', 'SAFETY', 'SUBCONTRACT']) await H.upload(page, code)
  await page.locator('[data-step="review"]').click(); await scan('vendor-review')
  await H.submit(page); await scan('vendor-receipt')
  await H.detail(page, r.ID, 'rachel'); await scan('requester-review')
  await page.locator('#sendBack').click(); await scan('send-back-dialog'); await page.keyboard.press('Escape')
  await page.locator('#reject').click(); await scan('reject-dialog'); await page.keyboard.press('Escape')
  await H.throughFinance(page, r.ID, true, scan)
  await page.locator('#approve').click()
  await H.expect.poll(async () => (await (await page.request.get(`/api/internal/requests/${r.ID}`)).json()).request.status).toBe('CREATED')
  await H.detail(page, r.ID, 'fiona'); await scan('created-request')
  await page.goto('/portal/'); await scan('vendor-created')
  await H.login(page, 'adam')
  for (const [hash, label] of [['/requests?view=all', 'requests'], ['/admin/sap-errors', 'sap-errors'], ['/admin/connection', 'connection'], ['/admin/config', 'configuration'], ['/admin/routes', 'approval-routes'], ['/mailbox', 'mailbox']]) {
    await page.goto('/internal/#' + hash); await page.reload(); await page.locator('#app .card, #app .list-card').first().waitFor(); await scan(label)
  }
  const cfg = await (await page.request.get('/api/internal/config')).json()
  const save = async routes => {
    await H.login(page, 'adam')
    const out = await page.request.put('/api/internal/admin/routes', { data: { routes, requesterReviewEnabled: true }, headers: { 'x-requested-with': 'VOB' } })
    H.expect(out.ok(), await out.text()).toBeTruthy()
  }
  try {
    await save([{ ID: 'SCREEN_LOW', priority: 1, name: 'Screen Finance call-back', active: true, accountTypes: 'YBIV', steps: 'PURCHASING,FINANCE', bankCheckMode: 'IN_FINANCE' }, ...cfg.approvalRoutes])
    await page.goto('/internal/?screen=routes#/admin/routes'); await page.locator('.route-card').first().waitFor(); await scan('route-finance-warning')
    await page.context().clearCookies({ name: 'vob_portal' })
    const low = await H.prepared(page)
    await H.approve(page, low.ID, 'rachel')
    await H.detail(page, low.ID, 'paddy'); await scan('purchasing')
    await H.approve(page, low.ID, 'paddy')
    await H.detail(page, low.ID, 'fiona'); await scan('finance-with-callback')
    await page.locator('#fillCallback').click(); await H.expect(page.locator('#bNum')).toHaveValue('+35315550100'); await page.locator('#bSave').click()
    await H.expect(page.locator('.banner.ok').filter({ hasText: 'Last call' })).toBeVisible()
    await scan('finance-callback-confirmed')
  } finally { await save(cfg.approvalRoutes) }
  await page.context().clearCookies({ name: 'vob_portal' })
  await page.goto('/portal/?t=invalid-token'); await page.locator('#send').click(); await scan('invalid-link')
  const response = await page.request.get('/')
  H.expect(response.headers()['content-security-policy']).toContain("script-src 'self'")
})
